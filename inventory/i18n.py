def set_lang(lang):
    """Set the output language. Raises ValueError for unsupported codes."""
    global LANG
    if lang not in TEXT:
        raise ValueError("unsupported language: %s" % lang)
    LANG = lang


def get_lang():
    return LANG


def t(key, **kw):
    """Translate a key. Falls back to English, then to the key itself."""
    value = TEXT.get(LANG, TEXT["en"]).get(key)
    if value is None:
        value = TEXT["en"].get(key, key)
    return value.format(**kw) if kw else value


def fmt_int(value):
    """Thousands separator according to the output language."""
    text = "{:,}".format(int(value))
    return text.replace(",", ".") if LANG == "es" else text

